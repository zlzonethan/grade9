create policy "authenticated users can read profiles" on public.profiles for select to authenticated using (true);
create policy "users can update own name" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "authenticated users can read subjects" on public.subjects for select to authenticated using (true);
create policy "staff can manage subjects" on public.subjects for all to authenticated using (public.current_user_role() in ('president', 'teacher')) with check (public.current_user_role() in ('president', 'teacher'));

create policy "authenticated users can read homework" on public.homework for select to authenticated using (archived_at is null);
create policy "staff can create homework" on public.homework for insert to authenticated with check (public.current_user_role() in ('president', 'teacher') and created_by = auth.uid());
create policy "staff can update homework" on public.homework for update to authenticated using (public.current_user_role() in ('president', 'teacher')) with check (public.current_user_role() in ('president', 'teacher'));
create policy "teachers can delete homework" on public.homework for delete to authenticated using (public.current_user_role() = 'teacher');

